// Builds ../assets/icons/sprite.svg from lucide-static (ISC licence).
//   node build-sprite.js
// Screens reference icons as <svg class="icon"><use href="../assets/icons/sprite.svg#i-NAME"/></svg>.
const fs = require('node:fs');
const path = require('node:path');

const ICONS = ['house', 'compass', 'route', 'trophy', 'message-square', 'ellipsis', 'search', 'newspaper',
  'settings', 'sun', 'moon', 'log-out', 'arrow-left', 'arrow-right', 'chevron-right', 'chevron-down', 'x',
  'check', 'eye', 'eye-off', 'sliders-horizontal', 'download', 'printer', 'send', 'square', 'brain', 'plus',
  'refresh-cw', 'lock', 'clock', 'calendar', 'map-pin', 'graduation-cap', 'sparkles', 'star', 'circle-alert',
  'info', 'external-link', 'user', 'school', 'book-open', 'briefcase', 'flame', 'medal', 'list-checks',
  'circle-help', 'trash-2', 'pencil'];

const ICON_DIR = path.join(__dirname, 'node_modules', 'lucide-static', 'icons');

function buildSprite(names) {
  const symbols = names.map(name => {
    const file = path.join(ICON_DIR, `${name}.svg`);
    if (!fs.existsSync(file)) throw new Error(`lucide-static has no icon "${name}"`);
    const svg = fs.readFileSync(file, 'utf8');
    const inner = svg.replace(/<!--[\s\S]*?-->/g, '').match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/i)[1].trim().replace(/\s*\n\s*/g, '');
    return `<symbol id="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide icons (ISC licence, see LICENSE.txt). Generated by tools/build-sprite.js; do not edit by hand. -->\n${symbols.join('\n')}\n</svg>\n`;
}

module.exports = { ICONS, buildSprite };

if (require.main === module) {
  const out = path.join(__dirname, '..', 'assets', 'icons');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'sprite.svg'), buildSprite(ICONS));
  fs.copyFileSync(path.join(__dirname, 'node_modules', 'lucide-static', 'LICENSE'), path.join(out, 'LICENSE.txt'));
  console.log(`sprite.svg: ${ICONS.length} icons`);
}
